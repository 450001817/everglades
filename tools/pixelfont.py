SPACE = 3

def glyph(ch, bold=False):
    rows = G[ch]
    w = len(rows[0])
    bits = [[c == '#' for c in r.ljust(w, '.')] for r in rows]
    if bold:
        bits = [[(r[i] if i < w else False) or (i > 0 and r[i - 1]) for i in range(w + 1)] for r in bits]
        w += 1
    return w, bits

def text_width(text, scale, bold=False):
    x = 0
    for ch in text:
        x += (SPACE if ch == ' ' else glyph(ch, bold)[0] + 1) * scale
    return x - scale

def draw_text(img, x, y, text, scale, color, bold=False):
    """Draws text with its cap-top at y. Returns the x after the text."""
    d = ImageDraw.Draw(img)
    for ch in text:
        if ch == ' ':
            x += SPACE * scale; continue
        w, bits = glyph(ch, bold)
        for r, row in enumerate(bits):
            for c, on in enumerate(row):
                if on: d.rectangle((x + c * scale, y + r * scale, x + (c + 1) * scale - 1, y + (r + 1) * scale - 1), fill=color)
        x += (w + 1) * scale
    return x - scale

def wrap(text, scale, width, bold=False):
    words, lines, cur = text.split(' '), [], ''
    for w in words:
        t = (cur + ' ' + w).strip()
        if text_width(t, scale, bold) <= width or not cur: cur = t
        else: lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines
